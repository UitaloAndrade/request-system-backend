CREATE TABLE solicitation_index_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    solicitation_id UUID NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMP WITH TIME ZONE,
    attempts INTEGER NOT NULL DEFAULT 0,
    last_error TEXT,
    next_attempt_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_solicitation_index_outbox PRIMARY KEY (id),
    CONSTRAINT ck_solicitation_index_outbox_event_type
        CHECK (event_type IN ('UPSERT'))
);

CREATE INDEX idx_solicitation_index_outbox_pending
    ON solicitation_index_outbox(processed_at, next_attempt_at, created_at);

-- When this migration is added to an existing database, enqueue every current
-- solicitation so the search index can be populated without manual data entry.
INSERT INTO solicitation_index_outbox (
    solicitation_id, event_type, created_at, attempts
)
SELECT id, 'UPSERT', CURRENT_TIMESTAMP, 0
FROM solicitations;
